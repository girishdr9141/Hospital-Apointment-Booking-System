-- =====================================================================
-- 16_global_sidecar_tables_and_seed.sql
-- PURPOSE :
--   Create the Global CarePulse Multi-Branch & Multi-Country Sidecar
--   Layer (strictly GBR_ prefixed tables).
--   ZERO existing GIRISH_* tables are altered.
--   ZERO existing constraints, indexes, or procedures are modified.
--   ZERO foreign keys point back into GIRISH_* tables (IDs are indexed
--   and validated inside GBR_* procedures so existing table deletes
--   or cleanups are never blocked by ORA-02292).
-- SAFE    : Idempotent (checks USER_TABLES / MERGE before DDL/DML).
-- RUN AS  : NOV_2026_BATCH in Oracle APEX SQL Workshop (Run Script / F5)
-- =====================================================================

-- ---------------------------------------------------------------------
-- PART 1: Create Core & Link GBR_ Tables
-- ---------------------------------------------------------------------
DECLARE
    v_cnt NUMBER := 0;
BEGIN
    -- 1. GBR_COUNTRIES
    SELECT COUNT(*) INTO v_cnt FROM USER_TABLES WHERE TABLE_NAME = 'GBR_COUNTRIES';
    IF v_cnt = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE GBR_COUNTRIES (
                COUNTRY_ID         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
                COUNTRY_CODE       VARCHAR2(10)   NOT NULL,
                COUNTRY_NAME       VARCHAR2(120)  NOT NULL,
                CURRENCY_CODE      VARCHAR2(10)   NOT NULL,
                CURRENCY_SYMBOL    VARCHAR2(10)   NOT NULL,
                PHONE_DIAL_CODE    VARCHAR2(15)   NOT NULL,
                DEFAULT_TIMEZONE   VARCHAR2(80)   NOT NULL,
                FX_RATE_TO_INR     NUMBER(14,6)   DEFAULT 1 NOT NULL,
                IS_ACTIVE          CHAR(1)        DEFAULT ''Y'' NOT NULL,
                CREATED_ON         TIMESTAMP(6)   DEFAULT CURRENT_TIMESTAMP NOT NULL,
                CONSTRAINT PK_GBR_COUNTRIES PRIMARY KEY (COUNTRY_ID),
                CONSTRAINT UQ_GBR_COUNTRY_CODE UNIQUE (COUNTRY_CODE),
                CONSTRAINT CHK_GBR_COUNTRY_ACT CHECK (IS_ACTIVE IN (''Y'', ''N'')),
                CONSTRAINT CHK_GBR_COUNTRY_FX CHECK (FX_RATE_TO_INR > 0)
            )
        ';
    END IF;

    -- 2. GBR_BRANCHES
    SELECT COUNT(*) INTO v_cnt FROM USER_TABLES WHERE TABLE_NAME = 'GBR_BRANCHES';
    IF v_cnt = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE GBR_BRANCHES (
                BRANCH_ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
                COUNTRY_ID         NUMBER         NOT NULL,
                BRANCH_CODE        VARCHAR2(30)   NOT NULL,
                BRANCH_NAME        VARCHAR2(160)  NOT NULL,
                CITY               VARCHAR2(120)  NOT NULL,
                ADDRESS_LINE       VARCHAR2(300),
                POSTAL_CODE        VARCHAR2(30),
                PHONE              VARCHAR2(40),
                EMAIL              VARCHAR2(160),
                TIMEZONE_IANA      VARCHAR2(80)   NOT NULL,
                CURRENCY_CODE      VARCHAR2(10)   NOT NULL,
                IS_HEADQUARTERS    CHAR(1)        DEFAULT ''N'' NOT NULL,
                IS_ACTIVE          CHAR(1)        DEFAULT ''Y'' NOT NULL,
                CREATED_ON         TIMESTAMP(6)   DEFAULT CURRENT_TIMESTAMP NOT NULL,
                CONSTRAINT PK_GBR_BRANCHES PRIMARY KEY (BRANCH_ID),
                CONSTRAINT UQ_GBR_BRANCH_CODE UNIQUE (BRANCH_CODE),
                CONSTRAINT FK_GBR_BRANCH_COUNTRY FOREIGN KEY (COUNTRY_ID) REFERENCES GBR_COUNTRIES (COUNTRY_ID),
                CONSTRAINT CHK_GBR_BRANCH_HQ CHECK (IS_HEADQUARTERS IN (''Y'', ''N'')),
                CONSTRAINT CHK_GBR_BRANCH_ACT CHECK (IS_ACTIVE IN (''Y'', ''N''))
            )
        ';
    END IF;

    -- 3. GBR_BRANCH_DEPARTMENTS (Specialized departments & local fees per branch)
    SELECT COUNT(*) INTO v_cnt FROM USER_TABLES WHERE TABLE_NAME = 'GBR_BRANCH_DEPARTMENTS';
    IF v_cnt = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE GBR_BRANCH_DEPARTMENTS (
                BRANCH_DEPT_ID         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
                BRANCH_ID              NUMBER        NOT NULL,
                DEPARTMENT_ID          NUMBER        NOT NULL,
                IS_SPECIALIZED         CHAR(1)       DEFAULT ''N'' NOT NULL,
                LOCAL_CONSULTATION_FEE NUMBER(12,2),
                IS_ACTIVE              CHAR(1)       DEFAULT ''Y'' NOT NULL,
                CREATED_ON             TIMESTAMP(6)  DEFAULT CURRENT_TIMESTAMP NOT NULL,
                CONSTRAINT PK_GBR_BRANCH_DEPTS PRIMARY KEY (BRANCH_DEPT_ID),
                CONSTRAINT UQ_GBR_BRANCH_DEPT UNIQUE (BRANCH_ID, DEPARTMENT_ID),
                CONSTRAINT FK_GBR_BD_BRANCH FOREIGN KEY (BRANCH_ID) REFERENCES GBR_BRANCHES (BRANCH_ID),
                CONSTRAINT CHK_GBR_BD_SPEC CHECK (IS_SPECIALIZED IN (''Y'', ''N'')),
                CONSTRAINT CHK_GBR_BD_ACT CHECK (IS_ACTIVE IN (''Y'', ''N''))
            )
        ';
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_GBR_BD_DEPT ON GBR_BRANCH_DEPARTMENTS (DEPARTMENT_ID)';
    END IF;

    -- 4. GBR_DOCTOR_BRANCHES (Many-to-many doctor assignments across branches)
    SELECT COUNT(*) INTO v_cnt FROM USER_TABLES WHERE TABLE_NAME = 'GBR_DOCTOR_BRANCHES';
    IF v_cnt = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE GBR_DOCTOR_BRANCHES (
                DOC_BRANCH_ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
                DOCTOR_ID              NUMBER        NOT NULL,
                BRANCH_ID              NUMBER        NOT NULL,
                IS_PRIMARY_BRANCH      CHAR(1)       DEFAULT ''N'' NOT NULL,
                LOCAL_CONSULTATION_FEE NUMBER(12,2),
                IS_ACTIVE              CHAR(1)       DEFAULT ''Y'' NOT NULL,
                CREATED_ON             TIMESTAMP(6)  DEFAULT CURRENT_TIMESTAMP NOT NULL,
                CONSTRAINT PK_GBR_DOCTOR_BRANCHES PRIMARY KEY (DOC_BRANCH_ID),
                CONSTRAINT UQ_GBR_DOC_BRANCH UNIQUE (DOCTOR_ID, BRANCH_ID),
                CONSTRAINT FK_GBR_DB_BRANCH FOREIGN KEY (BRANCH_ID) REFERENCES GBR_BRANCHES (BRANCH_ID),
                CONSTRAINT CHK_GBR_DB_PRIM CHECK (IS_PRIMARY_BRANCH IN (''Y'', ''N'')),
                CONSTRAINT CHK_GBR_DB_ACT CHECK (IS_ACTIVE IN (''Y'', ''N''))
            )
        ';
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_GBR_DB_DOCTOR ON GBR_DOCTOR_BRANCHES (DOCTOR_ID)';
    END IF;

    -- 5. GBR_SLOT_BRANCH (Slot -> Branch link)
    SELECT COUNT(*) INTO v_cnt FROM USER_TABLES WHERE TABLE_NAME = 'GBR_SLOT_BRANCH';
    IF v_cnt = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE GBR_SLOT_BRANCH (
                SLOT_BRANCH_ID   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
                SLOT_ID          NUMBER        NOT NULL,
                BRANCH_ID        NUMBER        NOT NULL,
                BRANCH_TIMEZONE  VARCHAR2(80)  NOT NULL,
                CREATED_ON       TIMESTAMP(6)  DEFAULT CURRENT_TIMESTAMP NOT NULL,
                CONSTRAINT PK_GBR_SLOT_BRANCH PRIMARY KEY (SLOT_BRANCH_ID),
                CONSTRAINT UQ_GBR_SB_SLOT UNIQUE (SLOT_ID),
                CONSTRAINT FK_GBR_SB_BRANCH FOREIGN KEY (BRANCH_ID) REFERENCES GBR_BRANCHES (BRANCH_ID)
            )
        ';
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_GBR_SB_BRANCH ON GBR_SLOT_BRANCH (BRANCH_ID)';
    END IF;

    -- 6. GBR_APPT_BRANCH (Appointment -> Branch link)
    SELECT COUNT(*) INTO v_cnt FROM USER_TABLES WHERE TABLE_NAME = 'GBR_APPT_BRANCH';
    IF v_cnt = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE GBR_APPT_BRANCH (
                APPT_BRANCH_ID     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
                APPOINTMENT_ID     NUMBER        NOT NULL,
                APPOINTMENT_REF    VARCHAR2(40),
                BRANCH_ID          NUMBER        NOT NULL,
                CONSULTATION_MODE  VARCHAR2(20)  DEFAULT ''FACE_TO_FACE'' NOT NULL,
                CREATED_ON         TIMESTAMP(6)  DEFAULT CURRENT_TIMESTAMP NOT NULL,
                CONSTRAINT PK_GBR_APPT_BRANCH PRIMARY KEY (APPT_BRANCH_ID),
                CONSTRAINT UQ_GBR_AB_APPT UNIQUE (APPOINTMENT_ID),
                CONSTRAINT FK_GBR_AB_BRANCH FOREIGN KEY (BRANCH_ID) REFERENCES GBR_BRANCHES (BRANCH_ID),
                CONSTRAINT CHK_GBR_AB_MODE CHECK (CONSULTATION_MODE IN (''ONLINE'', ''FACE_TO_FACE''))
            )
        ';
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_GBR_AB_BRANCH ON GBR_APPT_BRANCH (BRANCH_ID)';
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_GBR_AB_REF ON GBR_APPT_BRANCH (APPOINTMENT_REF)';
    END IF;

    -- 7. GBR_PATIENT_PROFILE (Patient -> Country / Home Branch / Address)
    SELECT COUNT(*) INTO v_cnt FROM USER_TABLES WHERE TABLE_NAME = 'GBR_PATIENT_PROFILE';
    IF v_cnt = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE GBR_PATIENT_PROFILE (
                PATIENT_PROFILE_ID  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
                PATIENT_ID          NUMBER         NOT NULL,
                COUNTRY_ID          NUMBER,
                HOME_BRANCH_ID      NUMBER,
                CITY                VARCHAR2(120),
                ADDRESS_LINE        VARCHAR2(300),
                POSTAL_CODE         VARCHAR2(30),
                PREFERRED_CURRENCY  VARCHAR2(10),
                UPDATED_ON          TIMESTAMP(6)   DEFAULT CURRENT_TIMESTAMP NOT NULL,
                CONSTRAINT PK_GBR_PATIENT_PROFILE PRIMARY KEY (PATIENT_PROFILE_ID),
                CONSTRAINT UQ_GBR_PP_PATIENT UNIQUE (PATIENT_ID),
                CONSTRAINT FK_GBR_PP_COUNTRY FOREIGN KEY (COUNTRY_ID) REFERENCES GBR_COUNTRIES (COUNTRY_ID),
                CONSTRAINT FK_GBR_PP_BRANCH FOREIGN KEY (HOME_BRANCH_ID) REFERENCES GBR_BRANCHES (BRANCH_ID)
            )
        ';
    END IF;

    -- 8. GBR_PAYMENT_BRANCH (Payment -> Branch & Local Currency Snapshot)
    SELECT COUNT(*) INTO v_cnt FROM USER_TABLES WHERE TABLE_NAME = 'GBR_PAYMENT_BRANCH';
    IF v_cnt = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE GBR_PAYMENT_BRANCH (
                PAYMENT_BRANCH_ID  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
                PAYMENT_ID         NUMBER        NOT NULL,
                APPOINTMENT_ID     NUMBER        NOT NULL,
                BRANCH_ID          NUMBER        NOT NULL,
                LOCAL_CURRENCY     VARCHAR2(10)  NOT NULL,
                LOCAL_AMOUNT       NUMBER(12,2)  NOT NULL,
                BASE_INR_AMOUNT    NUMBER(12,2)  NOT NULL,
                FX_RATE_TO_INR     NUMBER(14,6)  DEFAULT 1 NOT NULL,
                CREATED_ON         TIMESTAMP(6)  DEFAULT CURRENT_TIMESTAMP NOT NULL,
                CONSTRAINT PK_GBR_PAYMENT_BRANCH PRIMARY KEY (PAYMENT_BRANCH_ID),
                CONSTRAINT UQ_GBR_PB_PAYMENT UNIQUE (PAYMENT_ID),
                CONSTRAINT FK_GBR_PB_BRANCH FOREIGN KEY (BRANCH_ID) REFERENCES GBR_BRANCHES (BRANCH_ID)
            )
        ';
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_GBR_PB_APPT ON GBR_PAYMENT_BRANCH (APPOINTMENT_ID)';
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_GBR_PB_BRANCH ON GBR_PAYMENT_BRANCH (BRANCH_ID)';
    END IF;
END;
