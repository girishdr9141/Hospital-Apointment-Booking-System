-- ---------------------------------------------------------------------
-- PART 2: Seed Countries, Branches & Backfill Headquarters Links
-- ---------------------------------------------------------------------
MERGE INTO GBR_COUNTRIES tgt
USING (
    SELECT 'IN' AS country_code, 'India' AS country_name, 'INR' AS currency_code, 'Rs.' AS currency_symbol, '+91' AS phone_dial_code, 'Asia/Kolkata' AS default_timezone, 1 AS fx_rate_to_inr FROM DUAL UNION ALL
    SELECT 'AE', 'United Arab Emirates', 'AED', 'AED', '+971', 'Asia/Dubai', 22.85 FROM DUAL UNION ALL
    SELECT 'SG', 'Singapore', 'SGD', 'S$', '+65', 'Asia/Singapore', 62.50 FROM DUAL UNION ALL
    SELECT 'GB', 'United Kingdom', 'GBP', 'GBP', '+44', 'Europe/London', 106.40 FROM DUAL UNION ALL
    SELECT 'US', 'United States', 'USD', '$', '+1', 'America/New_York', 84.10 FROM DUAL
) src
ON (tgt.country_code = src.country_code)
WHEN MATCHED THEN
    UPDATE SET tgt.country_name = src.country_name,
               tgt.currency_code = src.currency_code,
               tgt.currency_symbol = src.currency_symbol,
               tgt.phone_dial_code = src.phone_dial_code,
               tgt.default_timezone = src.default_timezone,
               tgt.fx_rate_to_inr = src.fx_rate_to_inr,
               tgt.is_active = 'Y'
WHEN NOT MATCHED THEN
    INSERT (country_code, country_name, currency_code, currency_symbol, phone_dial_code, default_timezone, fx_rate_to_inr, is_active)
    VALUES (src.country_code, src.country_name, src.currency_code, src.currency_symbol, src.phone_dial_code, src.default_timezone, src.fx_rate_to_inr, 'Y');

DECLARE
    v_in_id NUMBER;
    v_ae_id NUMBER;
    v_sg_id NUMBER;
    v_gb_id NUMBER;
    v_us_id NUMBER;
    v_hq_id NUMBER;
BEGIN
    SELECT country_id INTO v_in_id FROM GBR_COUNTRIES WHERE country_code = 'IN';
    SELECT country_id INTO v_ae_id FROM GBR_COUNTRIES WHERE country_code = 'AE';
    SELECT country_id INTO v_sg_id FROM GBR_COUNTRIES WHERE country_code = 'SG';
    SELECT country_id INTO v_gb_id FROM GBR_COUNTRIES WHERE country_code = 'GB';
    SELECT country_id INTO v_us_id FROM GBR_COUNTRIES WHERE country_code = 'US';

    MERGE INTO GBR_BRANCHES tgt
    USING (
        SELECT v_in_id AS country_id, 'IN-BLR-HQ' AS branch_code, 'CarePulse Bengaluru Headquarters' AS branch_name, 'Bengaluru' AS city, '12 MG Road, Indiranagar' AS address_line, '560038' AS postal_code, '+91-80-4000-1000' AS phone, 'hq-blr@carepulse.global' AS email, 'Asia/Kolkata' AS timezone_iana, 'INR' AS currency_code, 'Y' AS is_headquarters FROM DUAL UNION ALL
        SELECT v_ae_id, 'AE-DXB-01', 'CarePulse Dubai Healthcare City', 'Dubai', 'Building 64, Al Razi Medical Complex', '505001', '+971-4-500-2200', 'dubai@carepulse.global', 'Asia/Dubai', 'AED', 'N' FROM DUAL UNION ALL
        SELECT v_sg_id, 'SG-ORC-01', 'CarePulse Singapore Orchard', 'Singapore', '290 Orchard Road, Paragon Medical', '238859', '+65-6500-3300', 'singapore@carepulse.global', 'Asia/Singapore', 'SGD', 'N' FROM DUAL UNION ALL
        SELECT v_gb_id, 'GB-LON-01', 'CarePulse London Harley Street', 'London', '88 Harley Street, Marylebone', 'W1G 7HR', '+44-20-7946-0911', 'london@carepulse.global', 'Europe/London', 'GBP', 'N' FROM DUAL UNION ALL
        SELECT v_us_id, 'US-NYC-01', 'CarePulse New York Midtown', 'New York', '535 Madison Avenue, Suite 400', '10022', '+1-212-555-0190', 'nyc@carepulse.global', 'America/New_York', 'USD', 'N' FROM DUAL
    ) src
    ON (tgt.branch_code = src.branch_code)
    WHEN MATCHED THEN
        UPDATE SET tgt.country_id = src.country_id,
                   tgt.branch_name = src.branch_name,
                   tgt.city = src.city,
                   tgt.address_line = src.address_line,
                   tgt.postal_code = src.postal_code,
                   tgt.phone = src.phone,
                   tgt.email = src.email,
                   tgt.timezone_iana = src.timezone_iana,
                   tgt.currency_code = src.currency_code,
                   tgt.is_headquarters = src.is_headquarters,
                   tgt.is_active = 'Y'
    WHEN NOT MATCHED THEN
        INSERT (country_id, branch_code, branch_name, city, address_line, postal_code, phone, email, timezone_iana, currency_code, is_headquarters, is_active)
        VALUES (src.country_id, src.branch_code, src.branch_name, src.city, src.address_line, src.postal_code, src.phone, src.email, src.timezone_iana, src.currency_code, src.is_headquarters, 'Y');

    SELECT branch_id INTO v_hq_id FROM GBR_BRANCHES WHERE branch_code = 'IN-BLR-HQ';

    -- Map all existing active GIRISH_DEPARTMENTS to HQ safely
    FOR dep IN (SELECT department_id FROM GIRISH_DEPARTMENTS WHERE IS_ACTIVE = 'Y') LOOP
        MERGE INTO GBR_BRANCH_DEPARTMENTS tgt
        USING (SELECT v_hq_id AS branch_id, dep.department_id AS department_id FROM DUAL) src
        ON (tgt.branch_id = src.branch_id AND tgt.department_id = src.department_id)
        WHEN NOT MATCHED THEN
            INSERT (branch_id, department_id, is_specialized, is_active)
            VALUES (src.branch_id, src.department_id, 'N', 'Y');
    END LOOP;

    -- Map all existing active GIRISH_DOCTORS to HQ as primary branch
    FOR doc IN (SELECT doctor_id, consultation_fee FROM GIRISH_DOCTORS WHERE IS_ACTIVE = 'Y') LOOP
        MERGE INTO GBR_DOCTOR_BRANCHES tgt
        USING (SELECT doc.doctor_id AS doctor_id, v_hq_id AS branch_id, doc.consultation_fee AS fee FROM DUAL) src
        ON (tgt.doctor_id = src.doctor_id AND tgt.branch_id = src.branch_id)
        WHEN NOT MATCHED THEN
            INSERT (doctor_id, branch_id, is_primary_branch, local_consultation_fee, is_active)
            VALUES (src.doctor_id, src.branch_id, 'Y', src.fee, 'Y');
    END LOOP;

    COMMIT;
END;
