CREATE OR REPLACE PROCEDURE GIRISH_DECIDE_DOCTOR_LEAVE
(
    P_LEAVE_ID      IN NUMBER,
    P_ADMIN_USER_ID IN NUMBER,
    P_DECISION      IN VARCHAR2,
    P_COMMENTS      IN VARCHAR2 DEFAULT NULL
)
AS
    V_DOCTOR_ID      NUMBER;
    V_REQUESTED_BY   NUMBER;
    V_LEAVE_STATUS   VARCHAR2(20);
    V_START_DATE     DATE;
    V_END_DATE       DATE;
    V_REQUEST_ID     NUMBER;
    V_APPROVAL_TYPE  NUMBER;
    V_COUNT          NUMBER;
    V_CONFLICT_COUNT NUMBER := 0;
    V_CONFLICT_IDS   VARCHAR2(1500) := '';
BEGIN
    IF UPPER(P_DECISION) NOT IN ('APPROVED', 'REJECTED') THEN
        RAISE_APPLICATION_ERROR(-20040, 'Invalid leave decision');
    END IF;

    SELECT COUNT(*)
    INTO V_COUNT
    FROM GIRISH_USERS U
    JOIN GIRISH_USER_ROLES UR ON UR.USER_ID = U.USER_ID
    JOIN GIRISH_ROLES R ON R.ROLE_ID = UR.ROLE_ID
    WHERE U.USER_ID = P_ADMIN_USER_ID
      AND U.IS_ACTIVE = 'Y'
      AND UR.IS_ACTIVE = 'Y'
      AND R.ROLE_NAME = 'ADMIN'
      AND R.IS_ACTIVE = 'Y';

    IF V_COUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20041, 'User is not an active administrator');
    END IF;

    SELECT DOCTOR_ID, REQUESTED_BY, LEAVE_STATUS, START_DATE, END_DATE
    INTO V_DOCTOR_ID, V_REQUESTED_BY, V_LEAVE_STATUS, V_START_DATE, V_END_DATE
    FROM GIRISH_DOCTOR_LEAVES
    WHERE LEAVE_ID = P_LEAVE_ID
    FOR UPDATE;

    IF V_LEAVE_STATUS <> 'PENDING' THEN
        RAISE_APPLICATION_ERROR(-20042, 'Leave request is not pending');
    END IF;

    IF UPPER(P_DECISION) = 'APPROVED' THEN
        -- Lock doctor's slots directly via GIRISH_SLOTS.DOCTOR_ID
        FOR R_SLOT IN (
            SELECT SLOT_ID
            FROM GIRISH_SLOTS
            WHERE DOCTOR_ID = V_DOCTOR_ID
              AND SLOT_DATE >= TRUNC(V_START_DATE)
              AND SLOT_DATE < TRUNC(V_END_DATE) + 1
            ORDER BY SLOT_ID
            FOR UPDATE OF STATUS
        ) LOOP
            NULL;
        END LOOP;

        -- Find confirmed appointments and active holds directly via GIRISH_SLOTS.DOCTOR_ID
        FOR R_CONFLICT IN (
            SELECT A.APPOINTMENT_ID
            FROM GIRISH_APPOINTMENTS A
            JOIN GIRISH_SLOTS S
                ON S.SLOT_ID = A.SLOT_ID
            WHERE S.DOCTOR_ID = V_DOCTOR_ID
              AND S.SLOT_DATE >= TRUNC(V_START_DATE)
              AND S.SLOT_DATE < TRUNC(V_END_DATE) + 1
              AND (
                    UPPER(A.STATUS) = 'CONFIRMED'
                    OR (
                        UPPER(A.STATUS) = 'HELD'
                        AND A.HOLD_EXPIRES_AT > CURRENT_TIMESTAMP
                    )
                  )
            ORDER BY A.APPOINTMENT_ID
        ) LOOP
            V_CONFLICT_COUNT := V_CONFLICT_COUNT + 1;
            IF NVL(LENGTH(V_CONFLICT_IDS), 0) < 1300 THEN
                IF V_CONFLICT_IDS IS NOT NULL THEN
                    V_CONFLICT_IDS := V_CONFLICT_IDS || ',';
                END IF;
                V_CONFLICT_IDS := V_CONFLICT_IDS || R_CONFLICT.APPOINTMENT_ID;
            END IF;
        END LOOP;

        IF V_CONFLICT_COUNT > 0 THEN
            RAISE_APPLICATION_ERROR(
                -20044,
                'Leave conflicts with active appointments. IDs: ' || V_CONFLICT_IDS || '. Total conflicts: ' || V_CONFLICT_COUNT
            );
        END IF;
    END IF;

    SELECT APPROVAL_TYPE_ID
    INTO V_APPROVAL_TYPE
    FROM GIRISH_APPROVAL_TYPES
    WHERE APPROVAL_TYPE_NAME = 'DOCTOR_LEAVE'
      AND IS_ACTIVE = 'Y';

    BEGIN
        SELECT REQUEST_ID
        INTO V_REQUEST_ID
        FROM GIRISH_APPROVAL_REQUESTS
        WHERE APPROVAL_TYPE_ID = V_APPROVAL_TYPE
          AND TARGET_TABLE = 'GIRISH_DOCTOR_LEAVES'
          AND TARGET_RECORD_ID = P_LEAVE_ID
        FOR UPDATE;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            INSERT INTO GIRISH_APPROVAL_REQUESTS (
                APPROVAL_TYPE_ID, REQUESTED_BY, ASSIGNED_TO,
                REQUEST_DESCRIPTION, TARGET_TABLE, TARGET_RECORD_ID, REQUEST_STATUS
            ) VALUES (
                V_APPROVAL_TYPE, V_REQUESTED_BY, P_ADMIN_USER_ID,
                'Doctor leave request #' || P_LEAVE_ID,
                'GIRISH_DOCTOR_LEAVES', P_LEAVE_ID, 'PENDING'
            )
            RETURNING REQUEST_ID INTO V_REQUEST_ID;

            INSERT INTO GIRISH_APPROVAL_HISTORY (
                REQUEST_ID, ACTION_BY, ACTION_NAME, COMMENTS
            ) VALUES (
                V_REQUEST_ID, V_REQUESTED_BY, 'SUBMITTED', 'Doctor leave request submitted'
            );
    END;

    SELECT COUNT(*)
    INTO V_COUNT
    FROM GIRISH_APPROVAL_REQUESTS
    WHERE REQUEST_ID = V_REQUEST_ID
      AND REQUEST_STATUS = 'PENDING';

    IF V_COUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20043, 'Approval request is not pending');
    END IF;

    UPDATE GIRISH_DOCTOR_LEAVES
    SET LEAVE_STATUS = UPPER(P_DECISION),
        APPROVED_BY = CASE WHEN UPPER(P_DECISION) = 'APPROVED' THEN P_ADMIN_USER_ID ELSE NULL END,
        APPROVED_ON = CASE WHEN UPPER(P_DECISION) = 'APPROVED' THEN CURRENT_TIMESTAMP ELSE NULL END
    WHERE LEAVE_ID = P_LEAVE_ID;

    UPDATE GIRISH_APPROVAL_REQUESTS
    SET REQUEST_STATUS = UPPER(P_DECISION),
        DECIDED_ON = CURRENT_TIMESTAMP,
        ASSIGNED_TO = P_ADMIN_USER_ID
    WHERE REQUEST_ID = V_REQUEST_ID;

    INSERT INTO GIRISH_APPROVAL_HISTORY (
        REQUEST_ID, ACTION_BY, ACTION_NAME, COMMENTS
    ) VALUES (
        V_REQUEST_ID, P_ADMIN_USER_ID, UPPER(P_DECISION), P_COMMENTS
    );

    IF UPPER(P_DECISION) = 'APPROVED' THEN
        UPDATE GIRISH_SLOTS S
        SET S.STATUS = 'CANCELLED',
            S.UPDATED_ON = CURRENT_TIMESTAMP
        WHERE S.DOCTOR_ID = V_DOCTOR_ID
          AND S.SLOT_DATE >= TRUNC(V_START_DATE)
          AND S.SLOT_DATE < TRUNC(V_END_DATE) + 1
          AND S.SLOT_DATE >= TRUNC(CAST((SYSTIMESTAMP AT TIME ZONE 'Asia/Kolkata') AS DATE))
          AND S.STATUS = 'AVAILABLE'
          AND S.BOOKED_PATIENTS = 0;
    END IF;
END GIRISH_DECIDE_DOCTOR_LEAVE;
