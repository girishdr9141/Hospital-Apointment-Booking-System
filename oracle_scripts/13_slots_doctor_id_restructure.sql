CREATE OR REPLACE PROCEDURE GIRISH_GENERATE_SLOTS
(
    P_DAYS IN NUMBER DEFAULT 30
)
AS
    V_IST_NOW        DATE := CAST((SYSTIMESTAMP AT TIME ZONE 'Asia/Kolkata') AS DATE);
    V_DATE           DATE;
    V_WEEKDAY        VARCHAR2(20);
    V_ON_LEAVE       NUMBER := 0;
    V_SESS_COUNT     NUMBER := 0;
    V_SESS_START     VARCHAR2(5);
    V_SESS_END       VARCHAR2(5);
    V_START_MINS     NUMBER;
    V_END_MINS       NUMBER;
    V_CURRENT_MINS   NUMBER;
    V_SLOT_DATE      DATE;
    V_S_TIME         VARCHAR2(5);
    V_E_TIME         VARCHAR2(5);
    V_SLOT_END_DT    DATE;
    V_INSERTED_COUNT NUMBER := 0;

    FUNCTION to_mins(p_hhmm IN VARCHAR2) RETURN NUMBER IS
    BEGIN
        RETURN TO_NUMBER(SUBSTR(TRIM(p_hhmm), 1, 2)) * 60 + TO_NUMBER(SUBSTR(TRIM(p_hhmm), 4, 2));
    END to_mins;

    FUNCTION to_hhmm(p_mins IN NUMBER) RETURN VARCHAR2 IS
        v_norm NUMBER := MOD(p_mins, 1440);
    BEGIN
        RETURN LPAD(TRUNC(v_norm / 60), 2, '0') || ':' || LPAD(MOD(v_norm, 60), 2, '0');
    END to_hhmm;
BEGIN
    IF P_DAYS IS NULL OR P_DAYS < 1 THEN
        RAISE_APPLICATION_ERROR(-20050, 'Number of days must be at least 1');
    END IF;

    FOR I IN 0 .. P_DAYS - 1 LOOP
        V_DATE    := TRUNC(V_IST_NOW) + I;
        V_WEEKDAY := TRIM(TO_CHAR(V_DATE, 'DAY', 'NLS_DATE_LANGUAGE=ENGLISH'));

        FOR SW IN (
            SELECT W.DOCTOR_ID, W.SESSIONS_JSON, W.SLOT_DURATION_MINS, W.WORKING_DAYS
            FROM GIRISH_DOCTOR_SHIFT_WINDOWS W
            JOIN GIRISH_DOCTORS D ON D.DOCTOR_ID = W.DOCTOR_ID
            WHERE W.IS_REGISTERED = 'Y'
              AND D.IS_ACTIVE = 'Y'
              AND INSTR(',' || UPPER(REPLACE(W.WORKING_DAYS, ' ', '')) || ',', ',' || UPPER(V_WEEKDAY) || ',') > 0
        ) LOOP
            SELECT COUNT(*) INTO V_ON_LEAVE
            FROM GIRISH_DOCTOR_LEAVES
            WHERE DOCTOR_ID = SW.DOCTOR_ID
              AND LEAVE_STATUS = 'APPROVED'
              AND V_DATE >= TRUNC(START_DATE)
              AND V_DATE < TRUNC(END_DATE) + 1;

            IF V_ON_LEAVE = 0 AND SW.SESSIONS_JSON IS NOT NULL AND SUBSTR(TRIM(SW.SESSIONS_JSON), 1, 1) = '[' THEN
                APEX_JSON.PARSE('{"s":' || SW.SESSIONS_JSON || '}');
                V_SESS_COUNT := NVL(APEX_JSON.GET_COUNT('s'), 0);

                FOR S_IDX IN 1 .. V_SESS_COUNT LOOP
                    V_SESS_START := APEX_JSON.GET_VARCHAR2('s[%d].start_time', S_IDX);
                    V_SESS_END   := APEX_JSON.GET_VARCHAR2('s[%d].end_time', S_IDX);

                    IF V_SESS_START IS NOT NULL AND V_SESS_END IS NOT NULL THEN
                        V_START_MINS := to_mins(V_SESS_START);
                        V_END_MINS   := to_mins(V_SESS_END);
                        IF V_END_MINS <= V_START_MINS THEN
                            V_END_MINS := V_END_MINS + 1440;
                        END IF;

                        V_CURRENT_MINS := V_START_MINS;
                        WHILE V_CURRENT_MINS + SW.SLOT_DURATION_MINS <= V_END_MINS LOOP
                            V_SLOT_DATE := V_DATE + TRUNC(V_CURRENT_MINS / 1440);
                            V_S_TIME    := to_hhmm(V_CURRENT_MINS);
                            V_E_TIME    := to_hhmm(V_CURRENT_MINS + SW.SLOT_DURATION_MINS);

                            V_SLOT_END_DT := TO_DATE(TO_CHAR(V_SLOT_DATE, 'YYYY-MM-DD') || ' ' || V_E_TIME, 'YYYY-MM-DD HH24:MI');
                            IF V_E_TIME < V_S_TIME THEN
                                V_SLOT_END_DT := V_SLOT_END_DT + 1;
                            END IF;

                            IF V_SLOT_END_DT > V_IST_NOW THEN
                                INSERT INTO GIRISH_SLOTS (
                                    DOCTOR_ID, TEMPLATE_ID, SLOT_DATE, START_TIME, END_TIME,
                                    MAX_PATIENTS_PER_SLOT, BOOKED_PATIENTS, STATUS
                                )
                                SELECT
                                    SW.DOCTOR_ID, NULL, V_SLOT_DATE, V_S_TIME, V_E_TIME,
                                    1, 0, 'AVAILABLE'
                                FROM DUAL
                                WHERE NOT EXISTS (
                                    SELECT 1
                                    FROM GIRISH_SLOTS S
                                    WHERE S.DOCTOR_ID = SW.DOCTOR_ID
                                      AND TRUNC(S.SLOT_DATE) = V_SLOT_DATE
                                      AND S.START_TIME = V_S_TIME
                                      AND S.STATUS <> 'CANCELLED'
                                );
                                V_INSERTED_COUNT := V_INSERTED_COUNT + SQL%ROWCOUNT;
                            END IF;

                            V_CURRENT_MINS := V_CURRENT_MINS + SW.SLOT_DURATION_MINS;
                        END LOOP;
                    END IF;
                END LOOP;
            END IF;
        END LOOP;
    END LOOP;

    DBMS_OUTPUT.PUT_LINE('Total new slots generated: ' || V_INSERTED_COUNT);
END GIRISH_GENERATE_SLOTS;
