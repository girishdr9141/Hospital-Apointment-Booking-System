-- =====================================================================
-- 13_slots_doctor_id_restructure.sql
-- PURPOSE :
--   Restructure GIRISH_SLOTS so DOCTOR_ID is stored directly as a
--   column and foreign key to GIRISH_DOCTORS(DOCTOR_ID), removing the
--   runtime dependency on GIRISH_SLOT_TEMPLATES / TEMPLATE_ID:
--     1) Add DOCTOR_ID to GIRISH_SLOTS + FK_GIRISH_SLOTS_DOCTOR.
--     2) Backfill DOCTOR_ID on existing slots from GIRISH_SLOT_TEMPLATES
--        (and legacy historical template map), then make TEMPLATE_ID
--        nullable and drop GIRISH_SLOT_TMPL_FK so GIRISH_SLOT_TEMPLATES
--        can be safely retired/dropped when desired.
--     3) Create IDX_GIRISH_SLOTS_DOCTOR_DATE (DOCTOR_ID, SLOT_DATE, START_TIME).
--     4) Update PL/SQL procedures to use GIRISH_SLOTS.DOCTOR_ID directly:
--          - GIRISH_BOOK_APPOINTMENT
--          - GIRISH_DECIDE_DOCTOR_LEAVE
--          - GIRISH_GENERATE_SLOTS (reads GIRISH_DOCTOR_SHIFT_WINDOWS)
--     5) Update ORDS handlers on module 'girish_opd_api':
--          - GET  slots
--          - POST slots
--          - POST slots/doctor-generate
--          - GET  reports/utilisation
--          - POST token_queue
-- SAFE    : Idempotent (checks USER_TAB_COLUMNS / USER_CONSTRAINTS /
--           USER_INDEXES / USER_TABLES before DDL).
-- RUN AS  : NOV_2026_BATCH in Oracle APEX SQL Workshop (Run Script / F5)
-- =====================================================================

-- ---------------------------------------------------------------------
-- PART 1: Restructure GIRISH_SLOTS & Ensure Shift Table Exists
-- ---------------------------------------------------------------------
DECLARE
    v_cnt           NUMBER := 0;
    v_tmpl_tbl_cnt  NUMBER := 0;
    v_nullable      VARCHAR2(1);
    v_null_docs     NUMBER := 0;
BEGIN
    -- Ensure GIRISH_DOCTOR_SHIFT_WINDOWS exists in case script 13 is run standalone
    SELECT COUNT(*) INTO v_cnt FROM USER_TABLES WHERE TABLE_NAME = 'GIRISH_DOCTOR_SHIFT_WINDOWS';
    IF v_cnt = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE GIRISH_DOCTOR_SHIFT_WINDOWS (
                SHIFT_ID           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
                DOCTOR_ID          NUMBER        NOT NULL,
                DOCTOR_NAME        VARCHAR2(200) NOT NULL,
                SESSIONS_JSON      CLOB          NOT NULL,
                SLOT_DURATION_MINS NUMBER        NOT NULL,
                WORKING_DAYS       VARCHAR2(200) NOT NULL,
                IS_REGISTERED      CHAR(1)       DEFAULT ''Y'' NOT NULL,
                REGISTERED_AT      TIMESTAMP(6)  DEFAULT CURRENT_TIMESTAMP NOT NULL,
                UPDATED_ON         TIMESTAMP(6)  DEFAULT CURRENT_TIMESTAMP NOT NULL,
                CONSTRAINT PK_GIRISH_DOC_SHIFT PRIMARY KEY (SHIFT_ID),
                CONSTRAINT UQ_GDSW_DOCTOR UNIQUE (DOCTOR_ID),
                CONSTRAINT CHK_GDSW_DUR CHECK (SLOT_DURATION_MINS BETWEEN 10 AND 120),
                CONSTRAINT CHK_GDSW_REG CHECK (IS_REGISTERED IN (''Y'', ''N'')),
                CONSTRAINT FK_GDSW_DOCTOR FOREIGN KEY (DOCTOR_ID) REFERENCES GIRISH_DOCTORS (DOCTOR_ID)
            )
        ';
    END IF;

    -- 1. Add DOCTOR_ID column to GIRISH_SLOTS if missing
    SELECT COUNT(*) INTO v_cnt
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'GIRISH_SLOTS'
      AND COLUMN_NAME = 'DOCTOR_ID';

    IF v_cnt = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE GIRISH_SLOTS ADD (DOCTOR_ID NUMBER NULL)';
    END IF;

    -- 2. Backfill DOCTOR_ID from GIRISH_SLOT_TEMPLATES if that table still exists
    SELECT COUNT(*) INTO v_tmpl_tbl_cnt
    FROM USER_TABLES
    WHERE TABLE_NAME = 'GIRISH_SLOT_TEMPLATES';

    IF v_tmpl_tbl_cnt > 0 THEN
        EXECUTE IMMEDIATE '
            UPDATE GIRISH_SLOTS s
            SET s.doctor_id = (
                SELECT t.doctor_id
                FROM GIRISH_SLOT_TEMPLATES t
                WHERE t.template_id = s.template_id
            )
            WHERE s.doctor_id IS NULL
              AND s.template_id IS NOT NULL
              AND EXISTS (
                  SELECT 1
                  FROM GIRISH_SLOT_TEMPLATES t
                  JOIN GIRISH_DOCTORS d ON d.doctor_id = t.doctor_id
                  WHERE t.template_id = s.template_id
              )
        ';
    END IF;

    -- 3. Backfill known historical template_id -> doctor_id mappings if any remain NULL
    EXECUTE IMMEDIATE '
        UPDATE GIRISH_SLOTS s
        SET s.doctor_id = CASE s.template_id
            WHEN 261 THEN 2
            WHEN 293 THEN 2
            WHEN 325 THEN 2
            WHEN 327 THEN 3
            WHEN 545 THEN 4
            ELSE NULL
        END
        WHERE s.doctor_id IS NULL
          AND s.template_id IN (261, 293, 325, 327, 545)
          AND EXISTS (
              SELECT 1
              FROM GIRISH_DOCTORS d
              WHERE d.doctor_id = CASE s.template_id
                  WHEN 261 THEN 2
                  WHEN 293 THEN 2
                  WHEN 325 THEN 2
                  WHEN 327 THEN 3
                  WHEN 545 THEN 4
              END
          )
    ';
    COMMIT;

    -- 4. Drop FK constraint(s) on GIRISH_SLOTS referencing GIRISH_SLOT_TEMPLATES
    FOR c IN (
        SELECT uc.constraint_name
        FROM USER_CONSTRAINTS uc
        JOIN USER_CONSTRAINTS rc ON rc.constraint_name = uc.r_constraint_name
        WHERE uc.table_name = 'GIRISH_SLOTS'
          AND uc.constraint_type = 'R'
          AND rc.table_name = 'GIRISH_SLOT_TEMPLATES'
    ) LOOP
        EXECUTE IMMEDIATE 'ALTER TABLE GIRISH_SLOTS DROP CONSTRAINT ' || c.constraint_name;
    END LOOP;

    -- 5. Make TEMPLATE_ID nullable so new slots do not need a template_id
    BEGIN
        SELECT nullable INTO v_nullable
        FROM USER_TAB_COLUMNS
        WHERE TABLE_NAME = 'GIRISH_SLOTS'
          AND COLUMN_NAME = 'TEMPLATE_ID';
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            v_nullable := 'Y';
    END;

    IF v_nullable = 'N' THEN
        EXECUTE IMMEDIATE 'ALTER TABLE GIRISH_SLOTS MODIFY (TEMPLATE_ID NULL)';
    END IF;

    -- 6. Add Foreign Key FK_GIRISH_SLOTS_DOCTOR -> GIRISH_DOCTORS(DOCTOR_ID)
    SELECT COUNT(*) INTO v_cnt
    FROM USER_CONSTRAINTS
    WHERE TABLE_NAME = 'GIRISH_SLOTS'
      AND CONSTRAINT_NAME = 'FK_GIRISH_SLOTS_DOCTOR';

    IF v_cnt = 0 THEN
        EXECUTE IMMEDIATE '
            ALTER TABLE GIRISH_SLOTS
            ADD CONSTRAINT FK_GIRISH_SLOTS_DOCTOR
            FOREIGN KEY (DOCTOR_ID) REFERENCES GIRISH_DOCTORS (DOCTOR_ID)
        ';
    END IF;

    -- 7. Enforce DOCTOR_ID NOT NULL if every existing row has a valid DOCTOR_ID
    --    (Must use EXECUTE IMMEDIATE because DOCTOR_ID may have been added dynamically above)
    EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM GIRISH_SLOTS WHERE DOCTOR_ID IS NULL'
        INTO v_null_docs;

    BEGIN
        SELECT nullable INTO v_nullable
        FROM USER_TAB_COLUMNS
        WHERE TABLE_NAME = 'GIRISH_SLOTS'
          AND COLUMN_NAME = 'DOCTOR_ID';
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            v_nullable := 'N';
    END;

    IF v_null_docs = 0 AND v_nullable = 'Y' THEN
        EXECUTE IMMEDIATE 'ALTER TABLE GIRISH_SLOTS MODIFY (DOCTOR_ID NOT NULL)';
    END IF;

    -- 8. Create composite index on (DOCTOR_ID, SLOT_DATE, START_TIME)
    SELECT COUNT(*) INTO v_cnt
    FROM USER_INDEXES
    WHERE INDEX_NAME = 'IDX_GIRISH_SLOTS_DOCTOR_DATE';

    IF v_cnt = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE INDEX IDX_GIRISH_SLOTS_DOCTOR_DATE
            ON GIRISH_SLOTS (DOCTOR_ID, SLOT_DATE, START_TIME)
        ';
    END IF;
END;
