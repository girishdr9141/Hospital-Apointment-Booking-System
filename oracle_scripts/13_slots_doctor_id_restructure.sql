CREATE OR REPLACE PROCEDURE GIRISH_BOOK_APPOINTMENT
(
    P_PATIENT_ID       IN NUMBER,
    P_SLOT_ID          IN NUMBER,
    P_BOOKING_SOURCE   IN VARCHAR2,
    P_APPOINTMENT_REF  OUT VARCHAR2
)
AS
    V_SLOT_STATUS       GIRISH_SLOTS.STATUS%TYPE;
    V_BOOKED            GIRISH_SLOTS.BOOKED_PATIENTS%TYPE;
    V_CAPACITY          GIRISH_SLOTS.MAX_PATIENTS_PER_SLOT%TYPE;
    V_SLOT_DATE         GIRISH_SLOTS.SLOT_DATE%TYPE;
    V_START_TIME        GIRISH_SLOTS.START_TIME%TYPE;
    V_END_TIME          GIRISH_SLOTS.END_TIME%TYPE;
    V_DOCTOR_ID         GIRISH_DOCTORS.DOCTOR_ID%TYPE;
    V_DEPARTMENT_ID     GIRISH_DOCTORS.DEPARTMENT_ID%TYPE;
    V_CONSULT_TYPE_ID   GIRISH_CONSULTATION_TYPES.CONSULTATION_TYPE_ID%TYPE;
    V_DURATION          GIRISH_CONSULTATION_TYPES.DURATION_MINS%TYPE;
    V_DOCTOR_ACTIVE     GIRISH_DOCTORS.IS_ACTIVE%TYPE;
    V_START_MINS        NUMBER;
    V_END_MINS          NUMBER;
    V_SLOT_END_DT       DATE;
    V_IST_NOW           DATE := CAST((SYSTIMESTAMP AT TIME ZONE 'Asia/Kolkata') AS DATE);
    V_COUNT             NUMBER;
    V_NEW_STATUS        VARCHAR2(20);
    V_HOLD_EXPIRY       TIMESTAMP;
BEGIN
    IF P_BOOKING_SOURCE NOT IN ('ONLINE', 'WALK_IN') THEN
        RAISE_APPLICATION_ERROR(-20001, 'Invalid booking source');
    END IF;

    SELECT
        S.STATUS,
        S.BOOKED_PATIENTS,
        S.MAX_PATIENTS_PER_SLOT,
        S.SLOT_DATE,
        S.START_TIME,
        NVL(S.END_TIME, S.START_TIME),
        S.DOCTOR_ID,
        D.DEPARTMENT_ID,
        D.IS_ACTIVE
    INTO
        V_SLOT_STATUS,
        V_BOOKED,
        V_CAPACITY,
        V_SLOT_DATE,
        V_START_TIME,
        V_END_TIME,
        V_DOCTOR_ID,
        V_DEPARTMENT_ID,
        V_DOCTOR_ACTIVE
    FROM GIRISH_SLOTS S
    JOIN GIRISH_DOCTORS D
        ON D.DOCTOR_ID = S.DOCTOR_ID
    WHERE S.SLOT_ID = P_SLOT_ID
    FOR UPDATE OF S.STATUS;

    -- Expire an old online hold if its 10-minute window has elapsed
    UPDATE GIRISH_APPOINTMENTS
    SET STATUS = 'CANCELLED',
        HOLD_EXPIRES_AT = NULL,
        UPDATED_ON = CURRENT_TIMESTAMP
    WHERE SLOT_ID = P_SLOT_ID
      AND STATUS = 'HELD'
      AND HOLD_EXPIRES_AT <= CURRENT_TIMESTAMP;

    IF SQL%ROWCOUNT > 0 THEN
        V_BOOKED := 0;
        V_SLOT_STATUS := 'AVAILABLE';

        UPDATE GIRISH_SLOTS
        SET BOOKED_PATIENTS = 0,
            STATUS = 'AVAILABLE',
            UPDATED_ON = CURRENT_TIMESTAMP
        WHERE SLOT_ID = P_SLOT_ID;
    END IF;

    IF V_DOCTOR_ACTIVE <> 'Y' THEN
        RAISE_APPLICATION_ERROR(-20002, 'Doctor is inactive');
    END IF;

    -- Evaluate IST end time (handles cross-midnight slots)
    V_SLOT_END_DT := TO_DATE(
        TO_CHAR(TRUNC(V_SLOT_DATE), 'YYYY-MM-DD') || ' ' || SUBSTR(TRIM(V_END_TIME), 1, 5),
        'YYYY-MM-DD HH24:MI'
    );
    IF SUBSTR(TRIM(V_END_TIME), 1, 5) < SUBSTR(TRIM(V_START_TIME), 1, 5) THEN
        V_SLOT_END_DT := V_SLOT_END_DT + 1;
    END IF;

    IF V_SLOT_END_DT <= V_IST_NOW THEN
        RAISE_APPLICATION_ERROR(-20003, 'Cannot book a past or expired slot');
    END IF;

    IF V_CAPACITY <> 1 OR V_BOOKED >= 1 OR V_SLOT_STATUS <> 'AVAILABLE' THEN
        RAISE_APPLICATION_ERROR(-20004, 'Slot is not available');
    END IF;

    -- Check approved doctor leave
    SELECT COUNT(*)
    INTO V_COUNT
    FROM GIRISH_DOCTOR_LEAVES
    WHERE DOCTOR_ID = V_DOCTOR_ID
      AND LEAVE_STATUS = 'APPROVED'
      AND TRUNC(V_SLOT_DATE) BETWEEN TRUNC(START_DATE) AND TRUNC(END_DATE);

    IF V_COUNT > 0 THEN
        RAISE_APPLICATION_ERROR(-20006, 'Doctor is on approved leave');
    END IF;

    SELECT COUNT(*)
    INTO V_COUNT
    FROM GIRISH_APPOINTMENTS
    WHERE SLOT_ID = P_SLOT_ID
      AND STATUS IN ('HELD', 'CONFIRMED');

    IF V_COUNT > 0 THEN
        RAISE_APPLICATION_ERROR(-20007, 'Slot already booked');
    END IF;

    -- Derive duration directly from slot START_TIME / END_TIME
    BEGIN
        V_START_MINS := TO_NUMBER(SUBSTR(TRIM(V_START_TIME), 1, 2)) * 60 + TO_NUMBER(SUBSTR(TRIM(V_START_TIME), 4, 2));
        V_END_MINS   := TO_NUMBER(SUBSTR(TRIM(V_END_TIME), 1, 2)) * 60 + TO_NUMBER(SUBSTR(TRIM(V_END_TIME), 4, 2));
        V_DURATION   := MOD((V_END_MINS - V_START_MINS + 1440), 1440);
        IF V_DURATION <= 0 THEN
            V_DURATION := 30;
        END IF;
    EXCEPTION
        WHEN OTHERS THEN
            V_DURATION := 30;
    END;

    -- Lookup default active consultation type for doctor's department (optional FK)
    BEGIN
        SELECT CONSULTATION_TYPE_ID
        INTO V_CONSULT_TYPE_ID
        FROM GIRISH_CONSULTATION_TYPES
        WHERE DEPARTMENT_ID = V_DEPARTMENT_ID
          AND IS_ACTIVE = 'Y'
          AND ROWNUM = 1;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            V_CONSULT_TYPE_ID := NULL;
    END;

    IF P_BOOKING_SOURCE = 'ONLINE' THEN
        V_NEW_STATUS := 'HELD';
        V_HOLD_EXPIRY := CURRENT_TIMESTAMP + INTERVAL '10' MINUTE;
    ELSE
        V_NEW_STATUS := 'CONFIRMED';
        V_HOLD_EXPIRY := NULL;
    END IF;

    P_APPOINTMENT_REF := 'APT' || SUBSTR(RAWTOHEX(SYS_GUID()), 1, 17);

    INSERT INTO GIRISH_APPOINTMENTS
    (
        APPOINTMENT_REF,
        PATIENT_ID,
        SLOT_ID,
        STATUS,
        HOLD_EXPIRES_AT,
        CONSULTATION_TYPE_ID,
        CONSULTATION_DURATION_MINS,
        BOOKING_SOURCE
    )
    VALUES
    (
        P_APPOINTMENT_REF,
        P_PATIENT_ID,
        P_SLOT_ID,
        V_NEW_STATUS,
        V_HOLD_EXPIRY,
        V_CONSULT_TYPE_ID,
        V_DURATION,
        P_BOOKING_SOURCE
    );

    UPDATE GIRISH_SLOTS
    SET BOOKED_PATIENTS = 1,
        STATUS = 'SOLD_OUT',
        UPDATED_ON = CURRENT_TIMESTAMP
    WHERE SLOT_ID = P_SLOT_ID;
END GIRISH_BOOK_APPOINTMENT;
